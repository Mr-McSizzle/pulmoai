def compute_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def get_git_history(rel_path: str) -> list[dict[str, str]]:
    history = []
    try:
        log_out = subprocess.check_output(
            ["git", "log", "--format=%h|%ad|%s", "--date=iso-strict", "--", rel_path],
            cwd=PROJECT_ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except subprocess.CalledProcessError:
        return history

    if not log_out:
        return history

    for line in log_out.splitlines():
        commit_hash, date, msg = line.split("|", 2)
        try:
            show_out = subprocess.check_output(
                ["git", "show", f"{commit_hash}:{rel_path}"],
                cwd=PROJECT_ROOT,
                stderr=subprocess.DEVNULL,
            )
            file_sha = hashlib.sha256(show_out).hexdigest()
            history.append({
                "commit": commit_hash,
                "date": date,
                "sha256": file_sha,
                "message": msg,
            })
        except subprocess.CalledProcessError:
            history.append({
                "commit": commit_hash,
                "date": date,
                "sha256": "DELETED_OR_UNTRACKED",
                "message": msg,
            })
    return history


